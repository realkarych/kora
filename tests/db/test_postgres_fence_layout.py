PRIVATE = "fence-layout-private-canary"
ALLOCATOR = "storage_address_fence_fence_incarnation_seq"
BACKEND = text("SELECT pg_catalog.pg_backend_pid()")
PERSISTENCE = text(
    "SELECT fence.relpersistence::text, allocator.relpersistence::text "
    "FROM pg_catalog.pg_class AS fence, pg_catalog.pg_class AS allocator "
    "WHERE fence.oid = pg_catalog.to_regclass('storage_address_fence') "
    "AND allocator.oid = pg_catalog.to_regclass("
    "pg_catalog.pg_get_serial_sequence('storage_address_fence', 'fence_incarnation'))"
)
TARGET_LOCKS = text(
    "SELECT pg_catalog.count(*) FROM pg_catalog.pg_locks "
    "WHERE pid = pg_catalog.pg_backend_pid() AND relation IN ("
    "pg_catalog.to_regclass('storage_address_fence'), "
    "pg_catalog.to_regclass('storage_address_fence_fence_incarnation_seq'))"
)


class DeliberateLayoutRollback(RuntimeError):
    pass


async def refuse_without_query(connection: AsyncConnection) -> None:
    with executed_queries(connection) as queries:
        outcome = await check_postgres_fence_layout(connection)

    assert outcome is PostgresFenceLayout.REFUSED
    assert queries == []


@pytest.mark.asyncio
async def test_postgres_fence_layout_checks_one_current_writer_without_allocating(
    database: Database,
) -> None:
    ledger = ConnectionLedger(database)

    async with database.read_transaction() as reader:
        await refuse_without_query(reader)
    async with database.transaction() as writer:
        if database.dialect is Dialect.SQLITE:
            await refuse_without_query(writer)
        else:
            backend: object = await writer.scalar(BACKEND)
            with executed_queries(writer) as queries:
                assert (
                    await check_postgres_fence_layout(writer)
                    is PostgresFenceLayout.VERIFIED
                )
            locks: object = await writer.scalar(TARGET_LOCKS)
            first = await insert_fence(writer, "layout-first")
            assert (
                await check_postgres_fence_layout(writer)
                is PostgresFenceLayout.VERIFIED
            )
            second = await insert_fence(writer, "layout-second")

            assert queries == [(POSTGRES_FENCE_LAYOUT.text, ())]
            assert type(backend) is int
            assert await writer.scalar(BACKEND) == backend
            assert locks == 0
            assert second == first + 1

    assert ledger.outstanding == database.units_in_flight() == 0


@pytest.mark.asyncio
@pytest.mark.parametrize(
    ("changes", "persistence"),
    [
        (
            (
                "ALTER TABLE storage_address_fence SET UNLOGGED",
                f"ALTER SEQUENCE {ALLOCATOR} SET LOGGED",
            ),
            ("u", "p"),
        ),
        ((f"ALTER SEQUENCE {ALLOCATOR} SET UNLOGGED",), ("p", "u")),
        (
            (
                f"ALTER SEQUENCE {ALLOCATOR} RENAME TO layout_owned_allocator",
                f"CREATE SEQUENCE {ALLOCATOR} AS bigint",
                "ALTER SEQUENCE layout_owned_allocator CYCLE",
            ),
            None,
        ),
        (
            (
                "ALTER TABLE storage_address_fence ALTER COLUMN "
                "fence_incarnation SET GENERATED BY DEFAULT",
            ),
            None,
        ),
        (("ALTER TABLE storage_address_fence RENAME TO layout_missing_fence",), None),
        (
            (
                "CREATE TEMP TABLE storage_address_fence ("
                "fence_incarnation bigint GENERATED ALWAYS AS IDENTITY)",
            ),
            ("t", "t"),
        ),
        (("SET TRANSACTION ISOLATION LEVEL REPEATABLE READ",), None),
    ],
    ids=[
        "unlogged-table",
        "unlogged-allocator",
        "cycled-owned-allocator-with-decoy",
        "identity-by-default",
        "missing-relation",
        "temporary-shadow",
        "old-transaction-snapshot",
    ],
)
async def test_postgres_fence_layout_refuses_native_drift_and_rolls_back(
    database: Database, changes: tuple[str, ...], persistence: tuple[str, str] | None
) -> None:
    ledger = ConnectionLedger(database)
    if database.dialect is Dialect.SQLITE:
        async with database.transaction() as writer:
            await refuse_without_query(writer)
        assert ledger.outstanding == database.units_in_flight() == 0
        return

    backend: object = None

    async def check_drift() -> None:
        nonlocal backend
        async with database.transaction() as writer:
            for change in changes:
                await writer.exec_driver_sql(change)
            backend = await writer.scalar(BACKEND)
            if persistence is not None:
                assert (await writer.execute(PERSISTENCE)).one() == persistence
            outcome = await check_postgres_fence_layout(writer)
            assert outcome is PostgresFenceLayout.REFUSED
            raise DeliberateLayoutRollback()

    with pytest.raises(DeliberateLayoutRollback):
        await check_drift()
    assert ledger.outstanding == database.units_in_flight() == 0
    async with database.transaction() as writer:
        assert await writer.scalar(BACKEND) == backend
        assert await check_postgres_fence_layout(writer) is PostgresFenceLayout.VERIFIED
        incarnation = await insert_fence(writer, "layout-after-drift")

    assert incarnation > 0
    assert ledger.outstanding == database.units_in_flight() == 0


@pytest.mark.asyncio
async def test_postgres_fence_layout_ignores_shadow_comparison_operator(
    database: Database,
) -> None:
    if database.dialect is Dialect.SQLITE:
        async with database.transaction() as writer:
            await refuse_without_query(writer)
        return

    async def compare_under_shadow() -> None:
        async with database.transaction() as writer:
            await writer.exec_driver_sql("CREATE SCHEMA layout_shadow")
            await writer.exec_driver_sql(
                'CREATE FUNCTION layout_shadow.compare(pg_catalog."char", '
                'pg_catalog."char") RETURNS boolean LANGUAGE plpgsql AS $$ '
                "BEGIN RAISE EXCEPTION 'shadow operator ran'; END $$"
            )
            await writer.exec_driver_sql(
                'CREATE OPERATOR layout_shadow.= (LEFTARG = pg_catalog."char", '
                'RIGHTARG = pg_catalog."char", FUNCTION = layout_shadow.compare)'
            )
            await writer.exec_driver_sql(
                "SET LOCAL search_path TO layout_shadow, pg_catalog, public"
            )
            with pytest.raises(DBAPIError, match="shadow operator ran"):
                async with writer.begin_nested():
                    await writer.exec_driver_sql(
                        """SELECT 'p'::pg_catalog."char" = 'p'::pg_catalog."char" """
                    )
            assert (
                await check_postgres_fence_layout(writer)
                is PostgresFenceLayout.VERIFIED
            )
            await writer.exec_driver_sql(f"ALTER SEQUENCE {ALLOCATOR} CYCLE")
            assert (
                await check_postgres_fence_layout(writer) is PostgresFenceLayout.REFUSED
            )
            raise DeliberateLayoutRollback()

    with pytest.raises(DeliberateLayoutRollback):
        await compare_under_shadow()
    async with database.transaction() as writer:
        assert await check_postgres_fence_layout(writer) is PostgresFenceLayout.VERIFIED


@pytest.mark.asyncio
async def test_postgres_fence_layout_refuses_nested_and_foreign_writer(
    database: Database,
) -> None:
    async with database.transaction() as writer:
        async with writer.begin_nested():
            await refuse_without_query(writer)
        await asyncio.create_task(refuse_without_query(writer))

        if database.dialect is Dialect.POSTGRESQL:
            assert (
                await check_postgres_fence_layout(writer)
                is PostgresFenceLayout.VERIFIED
            )
        else:
            await refuse_without_query(writer)


@pytest.mark.asyncio
async def test_postgres_fence_layout_driver_refusal_is_private_and_releases_writer(
    database: Database,
) -> None:
    ledger = ConnectionLedger(database)
    settings = LoggingSettings(
        level=Level.DEBUG,
        component_levels={DB_COMPONENT: Level.DEBUG},
        third_party={"sqlalchemy": Level.DEBUG},
    )

    async def refused_while_owned() -> None:
        async with database.transaction() as writer:
            if database.dialect is Dialect.POSTGRESQL:
                with pytest.raises(DBAPIError, match=PRIVATE):
                    await writer.exec_driver_sql(
                        "DO $$ BEGIN RAISE EXCEPTION "
                        "'fence-layout-private-canary'; END $$"
                    )
            try:
                raise RuntimeError(PRIVATE)
            except RuntimeError:
                outcome = await check_postgres_fence_layout(writer)
            assert outcome is PostgresFenceLayout.REFUSED
            raise DeliberateLayoutRollback()

    with captured(
        DB_COMPONENT, settings, "fence-layout-test", FakeClock().now
    ) as capture:
        with pytest.raises(DeliberateLayoutRollback) as rejected:
            await refused_while_owned()
        assert ledger.outstanding == database.units_in_flight() == 0
        async with database.transaction() as writer:
            if database.dialect is Dialect.POSTGRESQL:
                assert (
                    await check_postgres_fence_layout(writer)
                    is PostgresFenceLayout.VERIFIED
                )
            else:
                await refuse_without_query(writer)
            incarnation = await insert_fence(writer, "layout-after-native-refusal")
        records = capture.finish()
        raw_diagnostics = capture.reader.data

    assert rejected.value.__cause__ is rejected.value.__context__ is None
    assert incarnation > 0
    assert sum(record["event"] == "db.transaction.failed" for record in records) == 1
    assert any(
        record["event"] == "thirdparty.record"
        and str(record["logger"]).startswith("sqlalchemy")
        for record in records
    )
    for value in (
        PRIVATE,
        "pg_catalog.current_setting",
        "RAISE EXCEPTION",
        "InFailedSQLTransaction",
        "INSERT INTO",
    ):
        assert value.encode("utf-8") not in raw_diagnostics
    assert ledger.outstanding == database.units_in_flight() == 0
    assert database.writer_is_free()


@pytest.mark.asyncio
async def test_postgres_fence_layout_cancellation_releases_managed_writer(
    database: Database,
) -> None:
    if database.dialect is Dialect.SQLITE:
        async with database.transaction() as writer:
            await refuse_without_query(writer)
        return
    ledger = ConnectionLedger(database)
    engine = database.writer_engine.sync_engine
    admissions: list[int] = []

    def cancel_at_dispatch(
        connection: object, cursor: object, statement: str, *arguments: object
    ) -> None:
        if statement != POSTGRES_FENCE_LAYOUT.text:
            return
        owner = asyncio.current_task()
        assert owner is not None
        admissions.append(ledger.outstanding)
        asyncio.get_running_loop().call_soon(owner.cancel)

    async def check() -> None:
        async with database.transaction() as writer:
            assert (
                await check_postgres_fence_layout(writer)
                is PostgresFenceLayout.VERIFIED
            )

    event.listen(engine, "before_cursor_execute", cancel_at_dispatch)
    try:
        with pytest.raises(asyncio.CancelledError):
            await asyncio.wait_for(asyncio.create_task(check()), timeout=10)
    finally:
        event.remove(engine, "before_cursor_execute", cancel_at_dispatch)
    async with database.transaction() as writer:
        assert await check_postgres_fence_layout(writer) is PostgresFenceLayout.VERIFIED

    assert admissions == [1]
    assert ledger.outstanding == database.units_in_flight() == 0
    assert database.writer_is_free()
